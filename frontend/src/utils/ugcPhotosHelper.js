/**
 * Returns customer UGC photos specific to the product or category
 */
export function getProductUgcPhotos(product) {
  if (!product) return PRODUCT_UGC_MAP.default;
  if (PRODUCT_UGC_MAP[product.id]) {
    return PRODUCT_UGC_MAP[product.id];
  }
  const categoryKey = product.category || 'clothing';
  return PRODUCT_UGC_MAP[categoryKey] || PRODUCT_UGC_MAP.clothing || PRODUCT_UGC_MAP.default;
}

/**
 * Enriches reviews with matching customer photos from the UGC map
 */
export function enrichReviewsWithPhotos(reviews = [], product) {
  const ugcPhotos = getProductUgcPhotos(product);
  
  // Build a lookup by reviewer name (normalized lowercase)
  const photoByName = new Map();
  ugcPhotos.forEach((p) => {
    if (p.user) {
      photoByName.set(p.user.trim().toLowerCase(), p);
    }
  });

  return reviews.map((rev, index) => {
    // If the review already has its own images array with valid URLs, keep it
    if (rev.images && Array.isArray(rev.images) && rev.images.length > 0) {
      return rev;
    }

    const normName = (rev.userName || '').trim().toLowerCase();
    let matchedPhoto = photoByName.get(normName);

    // If not matched by exact name, match by partial name
    if (!matchedPhoto) {
      for (const [nameKey, p] of photoByName.entries()) {
        if (normName.includes(nameKey) || nameKey.includes(normName)) {
          matchedPhoto = p;
          break;
        }
      }
    }

    // If still not matched, attach available photos to the top reviews so photos are always visible
    if (!matchedPhoto && index < ugcPhotos.length && rev.rating >= 4) {
      matchedPhoto = ugcPhotos[index];
    }

    if (matchedPhoto) {
      return {
        ...rev,
        images: [matchedPhoto.url],
        photoData: {
          ...matchedPhoto,
          user: rev.userName || matchedPhoto.user,
          rating: rev.rating || matchedPhoto.rating,
          size: rev.sizeBought || matchedPhoto.size,
          caption: rev.text || matchedPhoto.caption
        }
      };
    }

    return rev;
  });
}
